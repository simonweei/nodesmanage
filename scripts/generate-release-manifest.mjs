import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const config = JSON.parse(await readFile(join(root, "scripts", "release-config.json"), "utf8"));
const mainGo = await readFile(join(root, "agent", "main.go"), "utf8");
const agentVersion = /version\s*=\s*"([^"]+)"/.exec(mainGo)?.[1];
if (!agentVersion) throw new Error("cannot read Agent version from agent/main.go");

const sha256 = async (path) => createHash("sha256").update(await readFile(path)).digest("hex");
const releases = {};
for (const arch of config.architectures) {
  const agentPath = join(root, "public", "downloads", `v${agentVersion}`, `nodemanage-agent-linux-${arch}`);
  const singBoxPath = join(root, "public", "downloads", `v${config.singBoxVersion}`, `sing-box-${config.singBoxVersion}-linux-${arch}.tar.gz`);
  releases[arch] = { agentSha256: await sha256(agentPath), singBoxSha256: await sha256(singBoxPath) };
}

const generated = `// Generated by scripts/generate-release-manifest.mjs. Do not edit.\nexport const AGENT_VERSION = ${JSON.stringify(agentVersion)};\nexport const SING_BOX_VERSION = ${JSON.stringify(config.singBoxVersion)};\nexport const RELEASE_DIGESTS = ${JSON.stringify(releases, null, 2)} as const;\n`;
const publicManifest = `${JSON.stringify({ schema_version: 1, channel: "stable", agent_version: agentVersion, sing_box_version: config.singBoxVersion, releases }, null, 2)}\n`;
const outputs = [
  [join(root, "src", "generated-releases.ts"), generated],
  [join(root, "public", "downloads", "stable.json"), publicManifest],
];

if (process.argv.includes("--check")) {
  for (const [path, expected] of outputs) {
    const actual = await readFile(path, "utf8").catch(() => "");
    if (actual !== expected) throw new Error(`${path} is stale; run npm run release:generate`);
  }
} else {
  for (const [path, content] of outputs) await writeFile(path, content, "utf8");
}
